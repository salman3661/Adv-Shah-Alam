let enrichedCount = 0;

for (const [slug, data] of Object.entries(enrichments)) {
  const filePath = path.join(postsDir, `${slug}.json`);
  if (!fs.existsSync(filePath)) {
    console.error(`File not found: ${slug}`);
    continue;
  }

  const post = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  // Add extra sections before the lawyer support section (or at the end)
  if (data.extraSections && data.extraSections.length > 0) {
    // Find lawyer section index
    const lawyerIdx = post.sections.findIndex(s => s.id.includes('lawyer') || s.id.includes('counsel') || s.id.includes('chamber'));
    if (lawyerIdx !== -1) {
      post.sections.splice(lawyerIdx, 0, ...data.extraSections);
    } else {
      post.sections.push(...data.extraSections);
    }

    // Update TOC
    data.extraSections.forEach(sec => {
      post.toc.push({ id: sec.id, title: sec.title });
    });
  }

  // Add extra FAQs
  if (data.extraFaqs && data.extraFaqs.length > 0) {
    post.faqs.push(...data.extraFaqs);
  }

  fs.writeFileSync(filePath, JSON.stringify(post, null, 2), 'utf8');
  enrichedCount++;
  console.log(`Enriched ${slug}`);
}

console.log(`\nSuccessfully enriched ${enrichedCount} posts!`);

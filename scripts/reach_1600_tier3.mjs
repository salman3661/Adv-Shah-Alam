let enrichedTier3Count = 0;

for (const [slug, data] of Object.entries(tier3)) {
  const filePath = path.join(postsDir, `${slug}.json`);
  if (!fs.existsSync(filePath)) continue;

  const post = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  if (data.section) {
    const lawyerIdx = post.sections.findIndex(s => s.id.includes('lawyer') || s.id.includes('counsel') || s.id.includes('chamber'));
    if (lawyerIdx !== -1) {
      post.sections.splice(lawyerIdx, 0, data.section);
    } else {
      post.sections.push(data.section);
    }
    post.toc.push({ id: data.section.id, title: data.section.title });
  }

  if (data.faqs && data.faqs.length > 0) {
    post.faqs.push(...data.faqs);
  }

  post.readTime = '15 min read';

  fs.writeFileSync(filePath, JSON.stringify(post, null, 2), 'utf8');
  enrichedTier3Count++;
  console.log(`Tier3 enriched ${slug}`);
}

